import { invalidInput } from './repository-error.js';

export function isExpenseIsoDate(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (match === null) return false;

  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  if (year < 1 || month < 1 || month > 12 || day < 1) return false;

  const leapYear = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const daysInMonth = [31, leapYear ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  return day <= (daysInMonth[month - 1] ?? 0);
}

export function expenseIsoDate(value: unknown, operation: string, field: string): string {
  if (!isExpenseIsoDate(value)) {
    throw invalidInput(operation, field, 'must be a valid YYYY-MM-DD date');
  }
  return value;
}
